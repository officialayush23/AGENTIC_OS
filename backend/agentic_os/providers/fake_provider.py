"""Deterministic fake provider for automated tests and keyless UI development.

Tests pass a `script` (list of responses consumed in order) or a `responder`
callable. Each response may be a dict (structured output), a str (text), a
ProviderError (raised), or a callable producing one of those.

Without a script, a small built-in responder answers connectivity checks and
returns a minimal one-step plan, so the UI can be exercised with no API key
when AGENTIC_OS_ENABLE_FAKE_PROVIDER=1.
"""

from __future__ import annotations

import json
import threading
from typing import Any, Callable, Iterator, List, Optional

from .base import ErrorCode, LLMProvider, LLMResult, ProviderCapabilities, ProviderConfig, ProviderError, Usage


def _default_responder(system: str, user: str, schema_name: str) -> Any:
    if schema_name == "connectivity_check":
        return {"ok": True, "echo": "agentic-os"}
    if schema_name == "plan":
        return {
            "goal": "Inspect the workspace (fake provider plan)",
            "assumptions": ["Generated by the fake provider for development."],
            "needs_clarification": False,
            "clarification_question": None,
            "steps": [
                {
                    "id": "list_files",
                    "title": "List workspace files",
                    "tool": "list_workspace_files",
                    "args": {"path": ".", "max_depth": 2},
                    "depends_on": [],
                    "expected_outcome": "A listing of the workspace",
                    "verification": None,
                }
            ],
            "completion_criteria": ["Workspace listing returned"],
        }
    if schema_name == "outcome_evaluation":
        return {"satisfied": True, "reason": "fake provider always agrees"}
    return "This is a deterministic response from the fake provider."


class FakeProvider(LLMProvider):
    kind = "fake"

    def __init__(
        self,
        config: Optional[ProviderConfig] = None,
        api_key: Optional[str] = None,
        *,
        script: Optional[List[Any]] = None,
        responder: Optional[Callable[[str, str, str], Any]] = None,
        use_default_responder: bool = True,
    ):
        config = config or ProviderConfig(id="fake", kind="fake", display_name="Fake", model="fake-model")
        super().__init__(config, api_key)
        self.script: List[Any] = list(script or [])
        self.responder = responder or (_default_responder if use_default_responder else None)
        self.calls: List[dict] = []
        self._lock = threading.Lock()

    def capabilities(self) -> ProviderCapabilities:
        return ProviderCapabilities(
            structured_modes=["json_object"], default_structured_mode="json_object",
            supports_streaming=True, supports_tool_calling=False, supports_json_schema=False,
            notes="Deterministic scripted provider for tests.",
        )

    def _next(self, system: str, user: str, schema_name: str) -> Any:
        with self._lock:
            if self.script:
                item = self.script.pop(0)
            elif self.responder is not None:
                item = self.responder
            else:
                raise ProviderError(ErrorCode.INVALID_OUTPUT, "fake provider script exhausted", provider_kind="fake")
        if callable(item) and not isinstance(item, (dict, list, str)):
            item = item(system, user, schema_name)
        if isinstance(item, BaseException):
            raise item
        return item

    def _call(self, system, user, *, schema, schema_name, mode, max_output_tokens) -> LLMResult:
        with self._lock:
            self.calls.append({"system": system, "user": user, "schema_name": schema_name, "mode": mode})
        item = self._next(system, user, schema_name)
        if isinstance(item, (dict, list)):
            text = json.dumps(item)
            data = item if (schema is not None and isinstance(item, dict)) else None
        else:
            text = str(item)
            data = None
        usage = Usage(input_tokens=max(1, (len(system) + len(user)) // 4), output_tokens=max(1, len(text) // 4))
        return LLMResult(
            text=text, data=data, usage=usage, latency_ms=1, model=self.config.model,
            provider_kind="fake", finish_reason="stop", mode=mode,
        )

    def _stream(self, system: str, user: str, *, max_output_tokens: int) -> Iterator[str]:
        result = self._call(system, user, schema=None, schema_name="text", mode="text", max_output_tokens=max_output_tokens)
        text = result.text
        for i in range(0, len(text), 40):
            yield text[i:i + 40]
